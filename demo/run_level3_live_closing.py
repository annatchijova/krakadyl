#!/usr/bin/env python3
"""Level 3 closing run: real SAM 3.1 calls on synthetic captures, judged by you.

`docs/level3-acquisition-contracts.md` closes Level 3 only with real
sensor execution, not fixtures:

  Run A — insufficiency: a real SAM call returns a technically valid
          result that does not discriminate the stated question.
          KRAKADYL must preserve the uncertainty and keep the
          requirement open (another route, or an explicit abstention).
  Run B — adversarial: a real SAM call returns a convincing annotation
          (a confident box around a clock) that still cannot answer
          the question. The script checks automatically that nothing
          was promoted before any human looks at it.

Both runs go through the unmodified gate, coordinator, write-once
repository and evaluation code, on a fresh, throwaway case store. You
are the evaluator: after each run the script shows what was captured
and what SAM returned, and asks you for the outcome. Your evaluation is
recorded as `investigator-C`, independent of the acquisition actor
`investigator-A` (both identities are ephemeral tokens created here).

What is sent to Meta: only two PNGs generated by this script (a plain
square; a drawn seven-segment clock reading 16:42), never case evidence.

Spend: exactly 2 image calls at the public USD 0.0025 each (2,500
micros). The run refuses to start unless --max-usd-micros covers that,
and the deployment budget is set to that same number, so the gate itself
blocks anything beyond it.

Live run (from the repo root, with the `api` extra installed):

    set -a; . ./.env; set +a          # provides META_API_KEY
    python demo/run_level3_live_closing.py --live \\
        --max-usd-micros 5000 --meta-retention-reviewed

Offline rehearsal (fake transport, no network, no spend):

    python demo/run_level3_live_closing.py --dry-run

Results land in out/level3-closing/<UTC timestamp>/: the two images, the
raw SAM candidates, and report.json with request IDs, digests, usage,
evaluations, and the requirement before/after each step.
"""

