from krakadyl.store import KrakadylStore  # noqa: E402

CALLS = 2
REQUIRED_USD_MICROS = CALLS * IMAGE_PRICE_USD_MICROS
OUT_ROOT = Path(__file__).resolve().parent.parent / "out" / "level3-closing"
ACTOR, EVALUATOR = "investigator-A", "investigator-C"


# --- synthetic images: stdlib PNG writer, nothing from real evidence ---

def _png(width: int, height: int, pixel) -> bytes:
    rows = bytearray()
    for y in range(height):
        rows.append(0)
        for x in range(width):
            rows.extend(pixel(x, y))

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(bytes(rows), 9)) + chunk(b"IEND", b"")


def plain_square_png() -> bytes:
    """Run A: no clock anywhere — 'digital clock' should find nothing useful."""
    return _png(640, 400, lambda x, y: (200, 40, 40) if 240 <= x < 400 and 120 <= y < 280 else (235, 235, 230))


_SEGMENTS = {  # a, b, c, d, e, f, g
    "0": "abcdef", "1": "bc", "2": "abged", "3": "abgcd", "4": "fgbc",
    "5": "afgcd", "6": "afgedc", "7": "abc", "8": "abcdefg", "9": "abcdfg",
}


def seven_segment_clock_png(text: str = "16:42") -> bytes:
    """Run B: a convincing clock face. SAM can box it confidently, but the
    picture holds no reference time, so it cannot answer the question."""
    width, height = 640, 400
    lit: set[tuple[int, int]] = set()
    digit_w, digit_h, thick = 70, 140, 14
    x0, y0 = 95, 130
    for ch in text:
        if ch == ":":
            for cy in (y0 + 40, y0 + 100):
                lit.update((x, y) for x in range(x0 + 10, x0 + 24) for y in range(cy, cy + 14))
            x0 += 40
            continue
        segs = _SEGMENTS[ch]
        rects = {
            "a": (x0, y0, digit_w, thick), "g": (x0, y0 + digit_h // 2 - thick // 2, digit_w, thick),
            "d": (x0, y0 + digit_h - thick, digit_w, thick), "f": (x0, y0, thick, digit_h // 2),
            "b": (x0 + digit_w - thick, y0, thick, digit_h // 2), "e": (x0, y0 + digit_h // 2, thick, digit_h // 2),
            "c": (x0 + digit_w - thick, y0 + digit_h // 2, thick, digit_h // 2),
        }
        for s in segs:
            rx, ry, rw, rh = rects[s]
            lit.update((x, y) for x in range(rx, rx + rw) for y in range(ry, ry + rh))
        x0 += digit_w + 30

    def pixel(x, y):
        if (x, y) in lit:
            return (255, 60, 40)
        if 70 <= x < 570 and 100 <= y < 300:
            return (20, 20, 22)  # the clock's dark face
        return (180, 180, 175)

    return _png(width, height, pixel)


# --- fake transport for --dry-run only ---

class _RehearsalSam:
    def __init__(self):
        self.calls = 0

    def __call__(self, url, headers, body, timeout):
        self.calls += 1
        text = "" if self.calls == 1 else (
            "<0f>1<|box;x1=70;y1=100;x2=569;y2=299;w=640;h=400;c=0.97|><|mask;x=0;y=0;data=2,3,~!!!!M|>"
        )
        result = {"id": f"rehearsal-{self.calls}", "status": "completed",
                  "output": [{"type": "message", "content": [{"type": "output_text", "text": text}]}]}
        return 200, {"x-request-id": f"rehearsal-{self.calls}"}, json.dumps(result).encode()


# --- the run ---

def _requirement(store) -> EvidenceRequirement:
    return store.get(CASE_ID, "requirement", CLOCK_REQUIREMENT_ID, EvidenceRequirement)


def _ask_outcome(label: str, scripted: str | None) -> tuple[EvaluationOutcome, str]:
    if scripted is not None:
        return EvaluationOutcome(scripted), "rehearsal: scripted outcome, not a human judgment"
    options = list(EvaluationOutcome)
    print(f"\n  Your evaluation of {label} — you are {EVALUATOR}, the independent evaluator:")
    for i, outcome in enumerate(options, 1):
        print(f"    {i}. {outcome.value}")
    while True:
        choice = input("  outcome number: ").strip()
        if choice.isdigit() and 1 <= int(choice) <= len(options):
            break
    while True:
        rationale = input("  rationale (what you saw, in your own words): ").strip()
        if rationale:
            return options[int(choice) - 1], rationale


def _one_run(name, image, sam_prompt, runtime, store, tokens, out_dir, report, scripted_outcome):
    print(f"\n=== {name} ===")
    (out_dir / f"{name}.png").write_bytes(image)
    before = _requirement(store)
    hypotheses_before = store.list(CASE_ID, "hypothesis", Hypothesis)
    proposal = runtime.build_proposal(
        case_id=CASE_ID, requirement=before, hypotheses=hypotheses_before,
        capture_mandate=store.get(CASE_ID, "mandate", CAPTURE_MANDATE_ID, Mandate),
        capture_instructions=f"Synthetic closing-run image for {name}; no case evidence.",
        sam_prompt=sam_prompt, now=datetime.now(timezone.utc),
    )
    grant = runtime.authorize(proposal, tokens[ACTOR], datetime.now(timezone.utc))
    entry = {"run": name, "sam_prompt": sam_prompt, "requirement_before": before.model_dump(mode="json")}
    try:
        result = runtime.acquire(proposal, grant, tokens[ACTOR], image)
    except SamAdapterError as exc:
        if getattr(exc, "dispatch_started", True) is not False:
            raise
        history = acquisition_history(store, CASE_ID)
        current = history[-1] if history else None
        attempt_state = current.attempts[-1].state if current and current.attempts else "unknown"
        entry.update({
            "outcome": "FAILED BEFORE DISPATCH — not retried",
            "failure_type": type(exc).__name__,
            "failure_reason": str(exc),
            "workflow_id": current.workflow.workflow_id if current else None,
            "attempt_state": attempt_state,
        })
        report["runs"].append(entry)
        print(f"  {entry['outcome']} ({entry['failure_reason']}). Stopping without another call.")
        return False
    except AcquisitionOutcomeUnknown as exc:
        entry["outcome"] = f"UNKNOWN after dispatch ({exc.phase.value}, attempt {exc.attempt_id}) — not retried"
        report["runs"].append(entry)
        print(f"  {entry['outcome']}. Stopping: reconcile it in the workspace before any further call.")
        return False

    candidate = runtime.artifacts.read_annotation(result.annotation)
    (out_dir / f"{name}.sam.txt").write_bytes(candidate)
    sidecar = parse_sam_annotation(candidate)
    history = next(h for h in acquisition_history(store, CASE_ID) if h.workflow.workflow_id == result.workflow.workflow_id)
    after_capture = _requirement(store)
    promoted = after_capture != before or store.list(CASE_ID, "hypothesis", Hypothesis) != hypotheses_before
    entry.update({
        "workflow_id": result.workflow.workflow_id,
        "observation_digest": result.observation.digest,
        "annotation_digest": result.annotation.output_digest,
        "annotation_empty": result.annotation.is_empty,
        "sidecar_status": sidecar.status,
        "sidecar_boxes": [[r.x1, r.y1, r.x2_inclusive, r.y2_inclusive, r.box_confidence] for r in sidecar.records],
        "provider_request_ids": [a.attempt.provider_request_id for a in history.attempts],
        "actual_usage": result.workflow.actual_usage.model_dump(mode="json"),
        "promoted_without_evaluation": promoted,
    })
    print(f"  captured sha256:{result.observation.digest[:16]}…  SAM: {sidecar.status}, "
          f"{len(sidecar.records)} region(s), request id {entry['provider_request_ids'][-1]}")
    for box in entry["sidecar_boxes"]:
        print(f"    box x1={box[0]} y1={box[1]} x2={box[2]} y2={box[3]} confidence={box[4]}")
    print(f"  files: {out_dir / (name + '.png')}  {out_dir / (name + '.sam.txt')}")
    if promoted:
        report["runs"].append(entry)
        raise SystemExit("FALSIFIED: the requirement or a hypothesis changed without an evaluation.")
    print("  check passed: requirement and hypotheses unchanged by capture + annotation alone")

    outcome, rationale = _ask_outcome(name, scripted_outcome)
    evaluation, after = record_evaluation(
        store, case_id=CASE_ID, workflow_id=result.workflow.workflow_id,
        expected_requirement_revision=requirement_revision_digest(after_capture),
        evaluator_identity=EVALUATOR, criterion_id="clock-within-one-minute", criterion_version="1",
        outcome=outcome, rationale=rationale, now=datetime.now(timezone.utc),
        verify_artifacts=runtime.artifacts.verify_for_evaluation,
    )
    entry.update({"evaluation": evaluation.model_dump(mode="json"), "requirement_after": after.model_dump(mode="json")})
    report["runs"].append(entry)
    state = "resolved" if after.resolved else "still open"
    print(f"  recorded {outcome.value} by {EVALUATOR}; requirement is {state}")
    return not after.resolved


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--live", action="store_true", help="make the two real, billed SAM calls")
    mode.add_argument("--dry-run", action="store_true", help="rehearse with a fake transport; no network")
    parser.add_argument("--max-usd-micros", type=int, default=0,
                        help=f"spend ceiling for --live; must be at least {REQUIRED_USD_MICROS}")
    parser.add_argument("--meta-retention-reviewed", action="store_true",
                        help="you checked Meta's current data-retention terms for SAM today")
    parser.add_argument("--scripted-outcome", choices=[o.value for o in EvaluationOutcome],
                        help="--dry-run only: skip the prompts and record this outcome for both runs")
    args = parser.parse_args()

    if args.live:
        if args.scripted_outcome:
            parser.error("--scripted-outcome is rehearsal-only; a live evaluation must be a human judgment")
        if not os.environ.get("META_API_KEY", "").strip():
            parser.error("META_API_KEY is not set; nothing was called")
        if args.max_usd_micros < REQUIRED_USD_MICROS:
            parser.error(f"--max-usd-micros must be at least {REQUIRED_USD_MICROS} ({CALLS} images); nothing was called")
        if not args.meta_retention_reviewed:
            parser.error("confirm --meta-retention-reviewed after checking Meta's current retention terms; nothing was called")
        if not sys.stdin.isatty():
            parser.error("--live requires an interactive terminal for the human evaluations; nothing was called")

    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out_dir = OUT_ROOT / (stamp + ("-dry-run" if args.dry_run else "-live"))
    out_dir.mkdir(parents=True)
    ceiling = args.max_usd_micros if args.live else REQUIRED_USD_MICROS
    rehearsal = _RehearsalSam() if args.dry_run else None
    processor = MetaSamProcessor(
        api_key=os.environ.get("META_API_KEY", "rehearsal-key") if args.live else "rehearsal-key",
        **({"transport": rehearsal} if rehearsal else {}),
    )
    usage_cap = ResourceUsage(usd_micros=ceiling, bytes=CALLS * 20 * 1024 * 1024, frames=0, duration_ms=CALLS * 180_000)
    tokens = {ACTOR: secrets.token_urlsafe(24), EVALUATOR: secrets.token_urlsafe(24)}

    with tempfile.TemporaryDirectory(prefix="krakadyl-closing-") as scratch:
        store = KrakadylStore(Path(scratch) / "case.db")
        ensure_seeded(store, Path(scratch))
        runtime = AcquisitionRuntime(
            store=store,
            credentials=OperatorCredentials.parse(";".join(f"{i}={hash_token(t)}" for i, t in tokens.items())),
            artifacts=FilesystemArtifactRepository(out_dir / "artifacts"),
            sam_processor=processor,
            budgets=ConfiguredBudgets(per_requirement=usage_cap, per_case_mandate=usage_cap, deployment=usage_cap),
        )
        report = {
            "mode": "live" if args.live else "dry-run",
            "started_at": datetime.now(timezone.utc).isoformat(),
            "usd_micros_ceiling": ceiling,
            "sent_to_meta": "two script-generated synthetic PNGs only" if args.live else "nothing",
            "runs": [],
        }
        print(f"Mode: {report['mode']}. Ceiling: {ceiling} USD micros. Output: {out_dir}")
        try:
            still_open = _one_run("run-A-insufficiency", plain_square_png(), "digital clock",
                                  runtime, store, tokens, out_dir, report, args.scripted_outcome)
            if still_open:
                _one_run("run-B-adversarial", seven_segment_clock_png(), "digital clock",
                         runtime, store, tokens, out_dir, report, args.scripted_outcome)
            elif report["runs"] and report["runs"][-1].get("outcome", "").startswith(
                ("UNKNOWN", "FAILED BEFORE DISPATCH")
            ):
                print("\nRun A did not settle; run B was not dispatched (no further spend).")
            else:
                print("\nRun A resolved the requirement, so run B was not dispatched (no further spend).")
        finally:
            report["finished_at"] = datetime.now(timezone.utc).isoformat()
            report["total_usd_micros"] = sum(r.get("actual_usage", {}).get("usd_micros", 0) for r in report["runs"])
            (out_dir / "report.json").write_text(json.dumps(report, indent=2, sort_keys=True))
            store.close()
    if rehearsal is not None:
        print(f"\nRehearsal: {rehearsal.calls} fake transport call(s), no network, nothing billed. The "
              f"{report['total_usd_micros']} USD micros in the report are the notional list price the adapter records.")
    else:
        print(f"\nSpend recorded at list price: {report['total_usd_micros']} USD micros "
              "(no account billing reconciliation was performed).")
    print(f"Report: {out_dir / 'report.json'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
